"""The committed golden loss trajectory (spec D3).

A determinism test that two runs in the *same process* agree tells you the seeding is
wired up. It cannot tell you that a refactor six months from now silently changed what
the model learns, because both sides of that comparison move together. This test pins
the trajectory itself: the losses live in a committed JSON file, and a run that departs
from them fails.

**On the tolerance.** The natural instinct is to demand bit-exactness. That would be a
cross-platform flake, not a test — the same PyTorch program produces slightly different
floats on different BLAS backends, CPU microarchitectures and thread counts, and CI runs
on hardware nobody controls. So the tolerance here is loose enough to survive that
(`rtol = 3%`) and the test is aimed at a different target: a change in *behaviour*.
Reordering an optimizer update, changing an init scale, or altering the data order all
move the trajectory far more than 3%. Bit-exactness on one machine is covered separately
by ``test_two_seeded_runs_are_identical``.

Regenerate after an intentional change with::

    python -m pytest tests/dynamics/test_golden_trajectory.py --update-golden
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pytest

from nanoscale.config import ExperimentConfig, TokenizerConfig, load_experiment
from nanoscale.data.toy import generate_corpus
from nanoscale.tokenizer import BPETokenizer
from nanoscale.train import Trainer

GOLDEN = Path(__file__).parent / "golden_trajectory.json"

#: Loose enough to survive a different BLAS backend, tight enough that any change to the
#: model, the optimizer, the schedule or the data order blows straight through it.
RTOL = 0.03


def _tokenizer() -> BPETokenizer:
    corpus = generate_corpus(seed=1, n_stories=1200)
    return BPETokenizer.train(corpus, TokenizerConfig(vocab_size=512, max_train_bytes=300_000))


def _config() -> ExperimentConfig:
    """The pinned run. Every field that affects the trajectory is written out here."""
    return load_experiment(
        tier="nano",
        overrides=[
            "tokenizer.vocab_size=512",
            "model.vocab_size=512",
            "model.n_layers=2",
            "model.d_model=64",
            "model.n_heads=2",
            "model.n_kv_heads=1",
            "model.max_seq_len=64",
            "data.seq_len=64",
            "data.val_fraction=0.1",
            "train.seed=1337",
            "train.device=cpu",
            "train.batch_size=4",
            "train.max_steps=40",
            "train.token_budget=null",
            "train.eval_interval=20",
            "train.log_interval=1",
            "train.ckpt_interval=10000",
        ],
    )


def _run(tmp_path: Path) -> list[float]:
    cfg = _config()
    result = Trainer(cfg, tokenizer=_tokenizer(), out_dir=tmp_path / "golden").train()
    return [float(row["loss"]) for row in result.history if "loss" in row]


def test_loss_trajectory_matches_the_committed_golden_run(
    tmp_path: Path, request: pytest.FixtureRequest
) -> None:
    """A seeded `nano`-shaped run must reproduce the committed loss trajectory."""
    losses = _run(tmp_path)

    if request.config.getoption("--update-golden"):
        GOLDEN.write_text(
            json.dumps(
                {
                    "note": (
                        "Generated by tests/dynamics/test_golden_trajectory.py "
                        "--update-golden. Do not hand-edit."
                    ),
                    "config_hash": _config().config_hash(),
                    "losses": [round(x, 6) for x in losses],
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
        pytest.skip("golden trajectory rewritten")

    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))

    # The config hash guards the *inputs*. If it changed, the trajectory is expected to
    # change too, and comparing losses would report a confusing failure instead of the
    # real one.
    assert _config().config_hash() == golden["config_hash"], (
        "the pinned config changed; regenerate with --update-golden and review the diff"
    )

    expected = golden["losses"]
    assert len(losses) == len(expected), f"logged {len(losses)} steps, golden has {len(expected)}"

    worst = max(abs(a - b) / max(b, 1e-9) for a, b in zip(losses, expected, strict=True))
    assert worst <= RTOL, (
        f"loss trajectory drifted by up to {worst:.2%} (tolerance {RTOL:.0%}).\n"
        f"  golden: {[round(x, 4) for x in expected[:6]]} ...\n"
        f"  actual: {[round(x, 4) for x in losses[:6]]} ...\n"
        "If the change was intentional, rerun with --update-golden and review the diff."
    )


def test_the_golden_run_starts_at_ln_vocab() -> None:
    """The committed trajectory must itself satisfy the zero-init prediction.

    Without this, a regenerated golden file could enshrine a broken run: the drift test
    above only compares against whatever is committed, so the committed thing needs at
    least one property checked against theory rather than against itself.
    """
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    assert golden["losses"][0] == pytest.approx(math.log(512), abs=0.02)
    assert golden["losses"][-1] < golden["losses"][0] - 0.5, "the golden run barely learned"
